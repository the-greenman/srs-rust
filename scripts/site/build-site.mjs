#!/usr/bin/env node
// Generate the CLI reference for engine.semanticops.com (srs-rust#1516) from a built `srs`:
// `srs --help`, then `srs <group> [<sub> ...] --help` for every command, recursively.
//
//   node scripts/site/build-site.mjs [path/to/srs]           write site/public/cli/*.md
//   node scripts/site/build-site.mjs --check [path/to/srs]   exit 1 if they differ from a fresh run
//
// The binary is the argument, else $SRS_BIN, else target/release/srs, else target/debug/srs.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = join(root, 'site/public/cli');
const args = process.argv.slice(2);
const check = args.includes('--check');
const bin =
  args.find((a) => a !== '--check') ??
  process.env.SRS_BIN ??
  ['target/release/srs', 'target/debug/srs'].map((p) => join(root, p)).find(existsSync);
if (!bin || !existsSync(bin)) {
  console.error('no srs binary: pass its path, set SRS_BIN, or run `cargo build -p srs`');
  process.exit(2);
}

const MARKER = '<!-- Generated by scripts/site/build-site.mjs from `srs --help`. Do not edit. -->';
const help = (path) =>
  execFileSync(bin, [...path, '--help'], {
    encoding: 'utf8',
    env: { ...process.env, COLUMNS: '100', NO_COLOR: '1', TERM: 'dumb' },
  }).trimEnd();

// The names under a help text's "Commands:" heading, minus clap's own `help`.
const subcommands = (text) => {
  const lines = text.split('\n');
  const start = lines.indexOf('Commands:');
  if (start < 0) return [];
  const names = [];
  for (const line of lines.slice(start + 1)) {
    const m = /^ {2}(\S+)/.exec(line);
    if (!m) break;
    if (m[1] !== 'help') names.push(m[1]);
  }
  return names;
};

const fence = (text) => '```text\n' + text + '\n```\n';

// One section per command under a group, depth-first in the binary's own order.
const sections = (path, level) => {
  const text = help(path);
  let md = `${'#'.repeat(level)} \`srs ${path.join(' ')}\`\n\n${fence(text)}\n`;
  for (const sub of subcommands(text)) md += sections([...path, sub], Math.min(level + 1, 6));
  return md;
};

const files = {};
const top = help([]);
const groups = subcommands(top);
files['index.md'] =
  `# srs CLI reference\n\n${MARKER}\n\n` +
  'Every command answers with a JSON envelope; see [start.md](../start.md) for the output contract.\n\n' +
  groups.map((g) => `- [\`srs ${g}\`](${g}.md)`).join('\n') +
  `\n\n## \`srs\`\n\n${fence(top)}`;
for (const g of groups) files[`${g}.md`] = `${MARKER}\n\n${sections([g], 1)}`.trimEnd() + '\n';

if (check) {
  const have = existsSync(outDir) ? readdirSync(outDir).sort() : [];
  const want = Object.keys(files).sort();
  const drift = [
    ...want.filter((f) => !have.includes(f) || readFileSync(join(outDir, f), 'utf8') !== files[f]),
    ...have.filter((f) => !want.includes(f)),
  ];
  if (drift.length) {
    console.error(`site/public/cli is out of date (${drift.join(', ')}): run node scripts/site/build-site.mjs`);
    process.exit(1);
  }
  console.log(`site/public/cli is up to date (${want.length} files)`);
} else {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  for (const [f, body] of Object.entries(files)) writeFileSync(join(outDir, f), body);
  console.log(`wrote ${Object.keys(files).length} files to site/public/cli`);
}
